#!/bin/sh
# Build a small recorded session. Compress the gap between two separate
# recordings while preserving packet order and the time within each recording.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
replay=$1
test_ui=$2
out=${3:-}

"$replay" < "$here/../docs/4baa79-position.tsv" > "$tmp/cpr"
awk 'NR==FNR {ts[$1]=$3; next} FNR==1 {start=ts[$1]} {print ts[$1]-start+1000,$2}' \
    "$here/../docs/4baa79-position.tsv" "$tmp/cpr" > "$tmp/frames"
gzip -dc "$here/fixtures/garden-and-bench.tsv.gz" |
    awk -F '\t' '$1==39355 || $1==39371 || $1==39379' > "$tmp/traffic"
cut -f1-5 "$tmp/traffic" | "$replay" > "$tmp/decoded"
awk 'NR==FNR {ts[$1]=$3; next} FNR==1 {start=ts[$1]} {print ts[$1]-start+4000,$2}' \
    "$tmp/traffic" "$tmp/decoded" >> "$tmp/frames"
test "$(wc -l < "$tmp/frames")" = 5
if [ -n "$out" ]; then
    mkdir -p "$out"
    "$test_ui" "$tmp/frames" "$here/../docs/4baa79-position.tsv" "$out"
    cp "$tmp/frames" "$out/replay-frames.txt"
    {
        printf '/* Generated by host/check-tdeck.sh from recorded, decoded DF17 frames. */\n'
        printf 'static const Card replay_cards[] = {\n'
        awk '{printf "    {.boot=REPLAY_BOOT,.ms=%d,.length=14,.word={", $1
              for(i=1;i<=length($2);i+=2) printf "%s0x%s", (i>1 ? "," : ""), substr($2,i,2)
              print "}},"}' "$tmp/frames"
        printf '};\n'
        awk 'NR==1 {printf "static const Capture replay_trace = {.dial_hz=1089800000,.floor=%d,.raw={", $4
                     for(i=1;i<=length($5);i+=2) printf "%s0x%s", (i>1 ? "," : ""), substr($5,i,2)
                     print "}};"}' "$here/../docs/4baa79-position.tsv"
    } > "$out/tdeck_replay_data.h"
else
    "$test_ui" "$tmp/frames" "$here/../docs/4baa79-position.tsv"
fi
