#!/usr/bin/env python3
"""Rasterize the T-Deck's ASCII and degree glyphs into packed 2-bit coverage."""
from argparse import ArgumentParser
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

parser = ArgumentParser(description=__doc__)
parser.add_argument("regular", type=Path)
parser.add_argument("bold", type=Path)
args = parser.parse_args()

ascii_glyphs = "".join(chr(i) for i in range(32, 127)) + "°"
faces = (
    ("small", args.regular, 13, ascii_glyphs),
    ("row", args.bold, 18, ascii_glyphs),
    ("name", args.bold, 27, ascii_glyphs),
    ("dial", args.bold, 32, " 0123456789,.-"),
    ("alt", args.bold, 44, " 0123456789,.-"),
)

print("/* Generated by tools/tdeck-font.py. See tdeck-font-OFL.txt. */")
for name, face, size, characters in faces:
    font = ImageFont.truetype(str(face), size, layout_engine=ImageFont.Layout.BASIC)
    image_bytes = bytearray()
    glyphs = []
    for char in characters:
        left, top, right, bottom = font.getbbox(char, anchor="ls")
        width, height = right - left, bottom - top
        image = Image.new("L", (width, height))
        if width and height:
            ImageDraw.Draw(image).text((-left, -top), char, fill=255, font=font, anchor="ls")
        packed = 0
        for index, value in enumerate(image.tobytes()):
            packed |= ((value + 42) // 85) << (2 * (index % 4))
            if index % 4 == 3:
                image_bytes.append(packed)
                packed = 0
        if width * height % 4:
            image_bytes.append(packed)
        glyphs.append((len(image_bytes) - (width * height + 3) // 4, left, top,
                       width, height, round(font.getlength(char))))
    print(f"static const uint8_t {name}_pixels[] = {{")
    for offset in range(0, len(image_bytes), 24):
        print("    " + ",".join(f"0x{x:02x}" for x in image_bytes[offset:offset + 24]) + ",")
    print("};")
    print(f"static const Glyph {name}_glyphs[] = {{")
    for values in glyphs:
        print("    {" + ",".join(map(str, values)) + "},")
    print("};")
    print(f'static const Font {name}_font = {{{name}_pixels,{name}_glyphs,{str(characters==ascii_glyphs).lower()}}};')
